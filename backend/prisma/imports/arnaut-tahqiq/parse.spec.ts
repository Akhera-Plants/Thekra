import { parseIhsan, parseMusnad } from './parse.js';

describe('parseMusnad', () => {
  const text = [
    '#META# bk: مسند أحمد - قرطبة',
    '~~7 - حدثنا عبد الله قال ثنا أبي قال ثنا أبو كامل عن أبي بكر الصديق أن النبي صلى',
    '~~الله عليه وسلم قال : السواك مطهرة للفم مرضاة للرب',
    '# تعليق شعيب الأرنؤوط : صحيح لغيره وهذا سند رجاله ثقات إلا أن فيه',
    '~~انقطاعا PageV01P003',
    '~~8 - حدثنا عبد الله ms0004 قال حدثني أبي عن أبي بكر الصديق قال قل اللهم إني ظلمت نفسي',
    '# تعليق شعيب الأرنؤوط : إسناده صحيح على شرط الشيخين PageV01P003',
    '~~9 - حدثنا عبد الله قال حدثني أبي عن عائشة لا نورث ما تركنا صدقة',
  ].join('\n');

  it('pairs each narration with the verdict that follows it, markers removed', () => {
    expect(parseMusnad(text)).toEqual([
      {
        number: 7,
        text: 'حدثنا عبد الله قال ثنا أبي قال ثنا أبو كامل عن أبي بكر الصديق أن النبي صلى الله عليه وسلم قال : السواك مطهرة للفم مرضاة للرب',
        verdict: 'صحيح لغيره وهذا سند رجاله ثقات إلا أن فيه انقطاعا',
      },
      {
        number: 8,
        text: 'حدثنا عبد الله قال حدثني أبي عن أبي بكر الصديق قال قل اللهم إني ظلمت نفسي',
        verdict: 'إسناده صحيح على شرط الشيخين',
      },
      { number: 9, text: 'حدثنا عبد الله قال حدثني أبي عن عائشة لا نورث ما تركنا صدقة', verdict: null },
    ]);
  });
});

describe('parseIhsan', () => {
  const text = [
    '### ||| AUTO ذكر البيان بأن النواهي سبيلها الحتم',
    '#  الدلالة على ندبيتها# 19 - حدثنا عمر بن محمد الهمداني، عن أبي هريرة، قال: § «إنما أهلك من كان قبلكم سؤالهم',
    '~~واختلافهم على أنبيائهم، فإذا نهيتكم -[200]- عن شيء، فاجتنبوه» [1: 2]',
    '# __________L',
    '# صحيح - «الإرواء» -أيضا-: ق.',
    '# S',
    '# إسناده صحيح على شرط الشيخين، وإسماعيل بن أبي أويس وإن كان متكلما فيه،',
    '~~فإن البخاري لم يخرج له إلا من صحيح حديثه.',
    '# تنبيه!!',
    'PageV01P201',
    '### ||| AUTO ذكر خبر آخر',
    '# 20 - أخبرنا فلان عن فلان قال: «حديث بلا تعليق للأرنؤوط»',
    '# __________L',
    '# ضعيف - «الضعيفة».',
  ].join('\n');

  it('reads the S block (Arna\'ut) and never the L block (al-Albani)', () => {
    const entries = parseIhsan(text);
    expect(entries.map((entry) => [entry.number, entry.verdict])).toEqual([
      [19, 'إسناده صحيح على شرط الشيخين، وإسماعيل بن أبي أويس وإن كان متكلما فيه، فإن البخاري لم يخرج له إلا من صحيح حديثه.'],
      [20, null],
    ]);
    expect(entries[0]!.text).toBe(
      'حدثنا عمر بن محمد الهمداني، عن أبي هريرة، قال: «إنما أهلك من كان قبلكم سؤالهم واختلافهم على أنبيائهم، فإذا نهيتكم عن شيء، فاجتنبوه»',
    );
    expect(entries.some((entry) => entry.text.includes('الإرواء') || entry.verdict?.includes('الإرواء'))).toBe(false);
  });
});
