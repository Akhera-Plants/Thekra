const NAME_TO_SURAH = new Map<string, number>();
for (const [surah, names] of SURAH_NAMES) {
  for (const name of names) NAME_TO_SURAH.set(foldSurahName(name), surah);
}

export function foldSurahName(name: string): string {
  return normalizeArabic(name)
    .replace(/^سور[هة]\s+/, '')
    .replace(/\s+/g, '');
}

function western(raw: string): number {
  const digits = raw
    .replace(/[\u0660-\u0669]/g, (char) => String(char.charCodeAt(0) - 0x0660))
    .replace(/[\u06F0-\u06F9]/g, (char) => String(char.charCodeAt(0) - 0x06f0));
  return Number(digits);
}

export interface VerseCitation {
  from: string;
  to: string;
}

const CITATION =
  /\[([^\[\]\d:]{1,40}?)\s*:\s*([0-9\u0660-\u0669\u06F0-\u06F9]{1,3})(?:\s*(?:[-–—]|إلى|الى|إلي)\s*([0-9\u0660-\u0669\u06F0-\u06F9]{1,3}))?\s*\]/g;

/** Every `[سورة: آية]` in the text, in the order printed. Unresolved names are dropped. */
export function extractCitations(text: string): VerseCitation[] {
  const found: VerseCitation[] = [];
  for (const match of text.matchAll(CITATION)) {
    const surah = NAME_TO_SURAH.get(foldSurahName(match[1] ?? ''));
    const start = western(match[2] ?? '');
    const end = match[3] ? western(match[3]) : start;
    const limit = surah ? AYAH_COUNT[surah - 1] : undefined;
    if (!surah || !limit || start < 1 || end < start || end > limit) continue;
    found.push({ from: `${surah}:${start}`, to: `${surah}:${end}` });
  }
  return found;
}
